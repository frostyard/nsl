"""Tests for the rendered Homebrew cask guard."""

import importlib.util
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("check_cask", ROOT / "scripts/check-cask.py")
check_cask = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(check_cask)

OLD_CASK = '''# This file was generated by GoReleaser. DO NOT EDIT.
cask "nsl" do
  version "0.12.0"

  on_linux do
    on_arm do
      sha256 "cf3398e186ea8b4cf29ceb81cea8cc1f2547eeb76c086c756a65eb897607dc41"
      url "https://github.com/frostyard/nsl/releases/download/v#{version}/nsl_linux_arm64.tar.gz"
    end
    on_intel do
      sha256 "c122767e02c11a969731d19f821681e96cbea6a425c31a3ad741dfe290b6308d"
      url "https://github.com/frostyard/nsl/releases/download/v#{version}/nsl_linux_amd64.tar.gz"
    end
  end

  name "nsl"
  desc "NSpawn Subsystem for Linux — development machines on atomic hosts"
  homepage "https://github.com/frostyard/nsl"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "nsl"

  # No zap stanza required

  caveats <<~EOS
    nsl requires an x86-64 Linux host with KVM, systemd-vmspawn, QEMU,
    UEFI firmware, virtiofsd and membership in the kvm group.
    Run nsl doctor to check host prerequisites; install them with your host's tools.
    Installation guide: https://frostyard.github.io/nsl/getting-started/install/
  EOS
end
'''


class CheckCask(unittest.TestCase):
    def test_old_cask_fails(self):
        found = check_cask.problems(OLD_CASK)
        self.assertTrue(found)
        self.assertTrue(any("Cask/ZapNotRequired" in problem or "zap :not_required" in problem for problem in found))

    def test_required_zap_passes(self):
        good = OLD_CASK.replace("  # No zap stanza required", "  zap :not_required")
        self.assertEqual(check_cask.problems(good), [])

    def test_no_zap_stanza_fails(self):
        text = OLD_CASK.replace("  # No zap stanza required\n", "")
        found = check_cask.problems(text)
        self.assertTrue(found)
        self.assertTrue(any("Cask/ZapNotRequired" in problem or "zap :not_required" in problem for problem in found))

    def test_cli_bad_and_good_files(self):
        with tempfile.TemporaryDirectory() as directory:
            bad = Path(directory) / "bad.rb"
            good = Path(directory) / "good.rb"
            bad.write_text(OLD_CASK, encoding="utf-8")
            good.write_text(OLD_CASK.replace("  # No zap stanza required", "  zap :not_required"), encoding="utf-8")
            bad_run = subprocess.run([sys.executable, str(ROOT / "scripts/check-cask.py"), str(bad)], capture_output=True, text=True)
            good_run = subprocess.run([sys.executable, str(ROOT / "scripts/check-cask.py"), str(good)], capture_output=True, text=True)
            self.assertEqual(bad_run.returncode, 1)
            self.assertIn("Cask/ZapNotRequired", bad_run.stderr)
            self.assertIn("1 cask checked", bad_run.stderr)
            self.assertEqual(good_run.returncode, 0)
            self.assertIn("1 cask checked, no problems:", good_run.stdout)

    def test_workflows_pin_exact_same_goreleaser_version(self):
        versions = {}
        counts = {"release.yml": 1, "test.yml": 2}
        for name, expected_count in counts.items():
            path = ROOT / ".github/workflows" / name
            text = path.read_text(encoding="utf-8")
            action_lines = [match.start() for match in re.finditer(r"(?m)^\s*(?:-\s*)?uses: goreleaser/goreleaser-action@", text)]
            found = []
            for start in action_lines:
                rest = text[start:].splitlines()
                block = rest[:1]
                for line in rest[1:]:
                    if re.match(r"^\s*- ", line):
                        break
                    block.append(line)
                found.extend(re.findall(r"(?m)^\s*version:\s*([^\s#]+)", "\n".join(block)))
            self.assertEqual(len(found), expected_count, (name, found))
            for version in found:
                self.assertRegex(version, r"^v\d+\.\d+\.\d+$")
            versions[name] = found
        all_versions = versions["release.yml"] + versions["test.yml"]
        self.assertEqual(len(set(all_versions)), 1)
        version_tuple = tuple(int(part) for part in all_versions[0][1:].split("."))
        self.assertGreaterEqual(version_tuple, (2, 20, 0))

    def test_workflows_render_and_check_cask(self):
        test = (ROOT / ".github/workflows/test.yml").read_text(encoding="utf-8")
        self.assertIn("python3 scripts/check-cask.py dist/homebrew/Casks/nsl.rb", test)
        self.assertIn("release --snapshot --clean", test)


if __name__ == "__main__":
    unittest.main()
